export const tQr = (language, key, replacements = {}) => {
    const dict = language === 'sw' ? sw : en;
    let text = dict[key] ?? en[key] ?? key;
    Object.keys(replacements).forEach((k) => {
        text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), replacements[k]);
    });
    return text;
};