export function tPost(language, key, replacements) {
    let str =
        postsTranslations[language]?.[key] ||
        postsTranslations.en?.[key] ||
        key;
    if (replacements) {
        Object.entries(replacements).forEach(([k, v]) => {
            str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
        });
    }
    return str;
}