export function tLogin(language, key, replacements) {
    let str =
        loginTranslations[language]?.[key] ||
        loginTranslations.en?.[key] ||
        key;
    if (replacements) {
        Object.entries(replacements).forEach(([k, v]) => {
            str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
        });
    }
    return str;
}